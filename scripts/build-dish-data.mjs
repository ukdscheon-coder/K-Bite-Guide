// Extracts the dish list from the app HTML inside dist/server/index.js and writes
// dist/server/dish-data.js. Run after changing dishes in the app:
//   node scripts/build-dish-data.mjs
// Workers cannot eval at runtime, so the data is extracted at build time.
import fs from "node:fs";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const serverDir = fileURLToPath(new URL("../dist/server/", import.meta.url));
const src = fs.readFileSync(serverDir + "index.js", "utf8");
const a = src.indexOf("const dishes = [");
const b = src.indexOf("const rules = [");
if (a < 0 || b < 0) throw new Error("dish block not found in dist/server/index.js");
// The block lives inside String.raw`...` so it is already plain JS source.
const ctx = {};
vm.createContext(ctx);
vm.runInContext(src.slice(a, b) + "\nglobalThis.__dishes = dishes;", ctx);
const dishes = ctx.__dishes.map((d) => ({
  id: d.id,
  emoji: d.emoji,
  ko: d.ko,
  phrase: d.phrase,
  meaning: d.meaning?.en || "",
  photo: d.photo || "",
  en: { name: d.text.en[0], desc: d.text.en[1], tags: d.text.en[2], steps: d.text.en[3] },
  otherNames: Object.fromEntries(
    Object.entries(d.text).filter(([k]) => k !== "en").map(([k, v]) => [k, v[0]])
  ),
}));
fs.writeFileSync(
  serverDir + "dish-data.js",
  "// Generated by scripts/build-dish-data.mjs — do not edit by hand.\nexport const dishes = " +
    JSON.stringify(dishes, null, 1) + ";\n"
);
console.log("wrote", dishes.length, "dishes");
